#!/usr/bin/env python3
"""Generate INSERT statements for scholarly_items from concepts_draft.jsonl.
Usage: python3 -I scripts/supabase/load_concepts_draft.py [in.jsonl] [out.sql]
Defaults: scholarly-assets/extraction-concepts/concepts_draft.jsonl -> scholarly-assets/extraction-concepts/load_concepts_draft.sql (gitignored)
- Rows are DRAFT / licence_cleared=false / riwayah_scope 'unspecified' only; anything else aborts generation (the DB trigger also blocks non-DRAFT/EXTRACTED inserts).
- Only metadata, neutral notes and lineage go in. The verbatim `fragment` quotes of variation entries are deliberately DROPPED: the DB gets
  source_id/unit_id/count only (the reader follows the unit id to the gitignored extraction for the text).
- Idempotent: a row is skipped if a concept with the same body.concept_key already exists.
- This script only writes a file. It never connects to any database; applying it to Supabase is the owner's decision."""
import sys, os, json
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, 'scholarly-assets', 'extraction-concepts')
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(D, 'concepts_draft.jsonl')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(D, 'load_concepts_draft.sql')
q = lambda s: "'" + s.replace("'", "''") + "'"
out = ['-- GENERATED by scripts/supabase/load_concepts_draft.py. DRAFT rows only; internal analysis; licence NOT cleared. Do not commit.', 'BEGIN;']
n = 0
for line in open(src, encoding='utf-8'):
    r = json.loads(line)
    assert r['kind'] == 'concept' and r['state'] == 'DRAFT' and r['licence_cleared'] is False and r['riwayah_scope'] == 'unspecified'
    body = dict(r['body'])
    if 'statements' in body:
        body['statements'] = [{k: v for k, v in s.items() if k != 'fragment'} for s in body['statements']]
    key = body['concept_key']
    arr = '{' + ','.join('"%s"' % u for u in r['source_unit_ids']) + '}'
    assert all(u.replace('"', '') == u for u in r['source_unit_ids'])
    out.append("INSERT INTO scholarly_items (kind, title_ar, title_en, body, source_unit_ids, riwayah_scope, state, licence_cleared)\n"
               "SELECT 'concept', %s, %s, %s::jsonb, %s::text[], 'unspecified', 'DRAFT', false\n"
               "WHERE NOT EXISTS (SELECT 1 FROM scholarly_items WHERE kind = 'concept' AND body->>'concept_key' = %s);"
               % (q(r['title_ar']), q(r['title_en']), q(json.dumps(body, ensure_ascii=False)), q(arr), q(key)))
    n += 1
out.append('COMMIT;')
open(dst, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('rows', n, '->', dst)
